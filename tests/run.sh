#!/bin/bash
# Lance les tests Luau (harnais Roblox simulé).
#
#   bash tests/run.sh                  tous les tests ; n'affiche que les échecs
#                                      puis "TESTS: N passed, M failed, K skipped"
#   bash tests/run.sh unit/maps        seuls les fichiers dont le chemin contient "unit/maps"
#   bash tests/run.sh sim::budget      ... et dont le nom de test contient "budget"
#   bash tests/run.sh --verbose        liste chaque test
#   bash tests/run.sh --list           liste les tests découverts, sans les exécuter
#
# Avant chaque exécution, ce script RÉGÉNÈRE depuis le disque (sans registre
# à maintenir à la main) :
#   tests/harness/_modules.generated.luau  tous les src/**/*.luau + leur place
#                                          dans l'arbre mock (selon default.project.json)
#   tests/_tests.generated.luau            tous les tests/**/*.test.luau (hors harness)
# Ces fichiers sont écrits de façon atomique (mktemp + mv) : plusieurs
# exécutions simultanées sont sans danger. Ne jamais les éditer.
#
# Variables : LUAU=/chemin/vers/luau   TEST_TIMEOUT=secondes (défaut 120)
# Compatible bash 3.2 (macOS) : pas de tableaux associatifs ni de mapfile.

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
cd "$root" || exit 2

LUAU="${LUAU:-$(command -v luau 2>/dev/null)}"
if [ -z "$LUAU" ]; then
  for candidate in /opt/homebrew/bin/luau /usr/local/bin/luau "$HOME/.local/bin/luau"; do
    if [ -x "$candidate" ]; then LUAU="$candidate"; break; fi
  done
fi
if [ -z "$LUAU" ] || [ ! -x "$LUAU" ]; then
  echo "luau introuvable : installe-le (brew install luau) ou exporte LUAU=/chemin/vers/luau" >&2
  echo "TESTS: 0 passed, 1 failed, 0 skipped (luau introuvable)"
  exit 2
fi

LC_ALL=C
export LC_ALL

# ---------------------------------------------------------------- génération --

# Choisit un niveau de crochets longs absent du fichier source.
long_open() { # $1 = fichier ; imprime le niveau (nombre de '=')
  local level=5
  while grep -qF "]$(printf '=%.0s' $(seq 1 $level))]" "$1" 2>/dev/null; do
    level=$((level + 1))
    if [ $level -gt 30 ]; then echo "impossible d'embarquer $1" >&2; exit 2; fi
  done
  echo $level
}

embed() { # $1 = fichier ; imprime la chaîne longue Luau contenant le fichier
  local level eq
  level="$(long_open "$1")"
  eq="$(printf '=%.0s' $(seq 1 "$level"))"
  # Le premier retour à la ligne d'une chaîne longue est ignoré : les numéros
  # de ligne du fichier restent donc exacts.
  printf '[%s[\n' "$eq"
  cat "$1"
  printf '\n]%s]' "$eq"
}

atomic_write() { # $1 = destination ; lit stdin
  local dest="$1" tmp
  tmp="$(mktemp "$(dirname "$dest")/.gen.XXXXXX")" || exit 2
  cat > "$tmp"
  chmod 644 "$tmp"
  if [ -f "$dest" ] && cmp -s "$tmp" "$dest"; then
    rm -f "$tmp"
  else
    mv -f "$tmp" "$dest"
  fi
}

# Table "chemin dans l'arbre<TAB>dossier source" lue dans default.project.json.
project_mappings() {
  awk '
    {
      line = $0
      opened = 0
      if (match(line, /"[^"]+"[ \t]*:[ \t]*\{/)) {
        key = substr(line, RSTART, RLENGTH)
        sub(/"[ \t]*:.*/, "", key); sub(/^"/, "", key)
        stack[++n] = key
        opened = 1
        rest = substr(line, RSTART + RLENGTH)
      }
      if (match(line, /"\$path"[ \t]*:[ \t]*"[^"]*"/)) {
        p = substr(line, RSTART, RLENGTH)
        sub(/^"\$path"[ \t]*:[ \t]*"/, "", p); sub(/"$/, "", p)
        path = ""
        for (i = 2; i <= n; i++) {
          if (stack[i] == "$properties") continue
          path = path (path == "" ? "" : "/") stack[i]
        }
        print path "\t" p
      }
      if (opened) {
        if (index(rest, "}") > 0) n--
      } else if (line ~ /^[ \t]*\}/ && n > 0) {
        n--
      }
    }
  ' default.project.json
}

generate_modules() {
  {
    echo "-- GENERATED by tests/run.sh — never edit by hand; regenerated on every run."
    echo "-- Every src/**/*.luau module with its location in the mock instance tree."
    echo "return {"
    project_mappings | while IFS="$(printf '\t')" read -r treepath srcdir; do
      [ -d "$srcdir" ] || continue
      find "$srcdir" -type f -name '*.luau' | sort | while IFS= read -r file; do
        rel="${file#$srcdir/}"
        dir="$(dirname "$rel")"
        base="$(basename "$rel")"
        name="${base%.luau}"
        class="ModuleScript"
        case "$name" in
          *.server) class="Script"; name="${name%.server}" ;;
          *.client) class="LocalScript"; name="${name%.client}" ;;
        esac
        full="$treepath"
        if [ "$dir" != "." ]; then full="$full/$dir"; fi
        full="$full/$name"
        tree=""
        oldifs="$IFS"; IFS="/"
        for part in $full; do tree="$tree\"$part\", "; done
        IFS="$oldifs"
        printf '\t{\n\t\tfile = "%s",\n\t\tclass = "%s",\n\t\ttree = { %s},\n\t\tsource = ' "$file" "$class" "$tree"
        embed "$file"
        printf ',\n\t},\n'
      done
    done
    echo "}"
  } | atomic_write "$here/harness/_modules.generated.luau"
}

generate_tests() {
  {
    echo "-- GENERATED by tests/run.sh — never edit by hand; regenerated on every run."
    echo "-- Every tests/**/*.test.luau file (the harness folder is excluded)."
    echo "return {"
    find tests -type f -name '*.test.luau' -not -path 'tests/harness/*' | sort | while IFS= read -r file; do
      rel="${file#tests/}"
      printf '\t{\n\t\tpath = "%s",\n\t\tsource = ' "${rel%.luau}"
      embed "$file"
      printf ',\n\t},\n'
    done
    echo "}"
  } | atomic_write "$here/_tests.generated.luau"
}

generate_modules
generate_tests

# ------------------------------------------------------------------ exécution --

timeout="${TEST_TIMEOUT:-120}"
out="$(mktemp "${TMPDIR:-/tmp}/mmtests.XXXXXX")" || exit 2
trap 'rm -f "$out"' EXIT

"$LUAU" tests/run_all.luau -a "$@" > "$out" 2>&1 &
pid=$!
# Chien de garde : tue luau après $timeout s. Ses sorties sont redirigées pour
# ne jamais retenir le tube d'un appelant (ex. `bash tests/run.sh | tail`).
( sleep "$timeout" >/dev/null 2>&1; kill -9 "$pid" >/dev/null 2>&1 ) >/dev/null 2>&1 &
watchdog=$!
{ wait "$pid"; } 2>/dev/null
status=$?
pkill -P "$watchdog" >/dev/null 2>&1
kill "$watchdog" >/dev/null 2>&1
wait "$watchdog" >/dev/null 2>&1

cat "$out"

summary="$(grep -E '^TESTS: ' "$out" | tail -1)"
if [ -z "$summary" ]; then
  echo "TESTS: 0 passed, 1 failed, 0 skipped (runner crashed or timed out after ${timeout}s, exit $status)"
  exit 1
fi
case "$summary" in
  *" listed "*) exit 0 ;;
esac
failed="$(echo "$summary" | sed -E 's/^TESTS: [0-9]+ passed, ([0-9]+) failed.*/\1/')"
if [ "$failed" != "0" ] || [ "$status" != "0" ]; then
  exit 1
fi
exit 0
